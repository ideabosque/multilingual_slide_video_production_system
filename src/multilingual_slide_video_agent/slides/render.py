"""Render every slide in a deck to a PNG screenshot via headless Chromium
(Playwright) - Agent 1's view of the original English deck (Claude cannot
interpret raw HTML/CSS any more than it can play video), and the frames of
the static-slideshow fallback.

Also `_inject_animation_assets`, which wires a deck's animation bundle into
slide pages (used by `msv slides extract-roles` in seek mode). The animated
video itself is rendered by the HyperFrames engine
(production/motion/hyperframes_engine.py); the Playwright live-capture
engine that used to record slides here was retired on 2026-10-22.
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path
from typing import Any

from multilingual_slide_video_agent.slides.extract_text import list_slide_files


class RenderError(Exception):
    pass


class AnimationCaptureError(RenderError):
    pass


def _parse_viewport(viewport: str) -> tuple[int, int]:
    try:
        width_s, height_s = viewport.lower().split("x")
        return int(width_s), int(height_s)
    except ValueError as e:
        raise RenderError(f"--viewport must look like '1920x1080', got '{viewport}'") from e


def render_deck_images(
    *,
    deck_dir: str | Path,
    out_dir: str | Path,
    viewport: str = "1920x1080",
) -> dict[str, Any]:
    from playwright.sync_api import sync_playwright

    deck_path = Path(deck_dir).resolve()
    out_path = Path(out_dir).resolve()
    out_path.mkdir(parents=True, exist_ok=True)
    width, height = _parse_viewport(viewport)

    slide_files = list_slide_files(deck_path)
    rendered = []
    with sync_playwright() as p:
        browser = p.chromium.launch()
        try:
            page = browser.new_page(viewport={"width": width, "height": height})
            for slide_path in slide_files:
                slide_id = slide_path.stem
                dest = out_path / f"{slide_id}.png"
                page.goto(slide_path.resolve().as_uri())
                page.screenshot(path=str(dest))
                rendered.append({"slide_id": slide_id, "image": str(dest)})
            page.close()
        finally:
            browser.close()

    manifest = {
        "deck_dir": str(deck_path),
        "out_dir": str(out_path),
        "viewport": {"width": width, "height": height},
        "slides": rendered,
    }
    (out_path / "render_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    return manifest


_ANIMATION_MARKER_START = "<!-- ANIMATION-OVERRIDE -->"
_ANIMATION_MARKER_END = "<!-- /ANIMATION-OVERRIDE -->"
_ANIMATION_ASSET_FILES = ("gsap.min.js", "animation_runtime.js", "design_tokens.css", "templates_config.js")

def _animation_asset_source(animation_dir: Path, name: str) -> Path:
    """Where to copy one animation asset from. The runtime code
    (animation_runtime.js, gsap.min.js) always comes from the installed
    package, so a bundle generated by an older version never runs stale code
    against today's injection (a September bundle's runtime once broke a
    real-deck render). Per-deck data (design_tokens.css,
    templates_config.js) still comes from the bundle, which is what
    `generate-animation` decided for that deck."""
    from multilingual_slide_video_agent.slides import generate_animation as ga

    package_code = {
        ga.ANIMATION_JS_NAME: ga._ASSETS_DIR / ga.ANIMATION_JS_NAME,
        ga.GSAP_JS_NAME: ga._VENDOR_DIR / ga.GSAP_JS_NAME,
    }
    return package_code.get(name, animation_dir / name)


def _inject_animation_assets(
    translated_deck_dir: Path, animation_dir: Path, template_by_slide: dict[str, str],
    motion_mode: str = "live", durations_by_slide_id: dict[str, float] | None = None,
) -> None:
    """Copy the deck's animation bundle into a deck directory and inject the
    <script>/<link> tags each slide page needs, idempotently (re-running
    replaces the prior injection by marker, the same pattern
    slides/cjk_fonts.py uses).

    `motion_mode` is animation_runtime.js's build-mode flag: "live" plays
    the timeline when the page opens; "seek" builds it paused and registers
    it as `window.__timelines[<slide_id>]` (`msv slides extract-roles` uses
    it so text is read before any tween has run)."""
    for name in _ANIMATION_ASSET_FILES:
        shutil.copy2(_animation_asset_source(animation_dir, name), translated_deck_dir / name)

    for slide_path in list_slide_files(translated_deck_dir):
        slide_id = slide_path.stem
        template = template_by_slide.get(slide_id)
        if template is None:
            raise AnimationCaptureError(
                f"no animation template assigned for slide '{slide_id}' - "
                f"the animation bundle at {animation_dir} doesn't match this deck's slides"
            )
        html = slide_path.read_text(encoding="utf-8")
        html = re.sub(
            re.escape(_ANIMATION_MARKER_START) + r".*?" + re.escape(_ANIMATION_MARKER_END) + r"\n?",
            "", html, flags=re.DOTALL,
        )
        # The inline `<style>` is render-blocking: the page stays invisible
        # until animation_runtime.js's run() reveals it, right after GSAP
        # applies the timeline's "from" starting values, so the first paint
        # never shows the slide at its final state.
        override = (
            f"{_ANIMATION_MARKER_START}\n"
            "<style>html{visibility:hidden}</style>\n"
            '<link rel="stylesheet" href="design_tokens.css">\n'
            f'<script>window.__ANIMATION_TEMPLATE__="{template}";'
            + (
                f'window.__MOTION_MODE__="seek";window.__ANIMATION_SLIDE_ID__="{slide_id}";'
                if motion_mode == "seek" else ""
            )
            # The slide's real on-screen length, which beat positions and
            # exits are laid out against.
            + (f"window.__ANIMATION_SLIDE_DURATION__={float(durations_by_slide_id[slide_id]):.6f};"
               if durations_by_slide_id and slide_id in durations_by_slide_id else "")
            + '</script>\n'
            '<script src="templates_config.js"></script>\n'
            '<script src="gsap.min.js"></script>\n'
            '<script src="animation_runtime.js" defer></script>\n'
            f"{_ANIMATION_MARKER_END}\n"
        )
        html = html.replace("</head>", override + "</head>", 1)
        slide_path.write_text(html, encoding="utf-8")


def chromium_available() -> list[str]:
    """Missing prerequisites for Chromium rendering (slide screenshots,
    role extraction); an empty list means ready. Never raises."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return ["playwright package not installed (pip install playwright)"]
    try:
        with sync_playwright() as p:
            exe = Path(p.chromium.executable_path)
    except Exception as e:  # noqa: BLE001 - availability checks must never raise
        return [f"playwright chromium unavailable: {e}"]
    if not exe.exists():
        return [f"playwright chromium binaries not found at {exe} (run: playwright install chromium)"]
    return []
